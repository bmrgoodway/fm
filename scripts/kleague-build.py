def lum(hexc):
    r,g,b = int(hexc[1:3],16), int(hexc[3:5],16), int(hexc[5:7],16)
    return (0.2126*r + 0.7152*g + 0.0722*b) / 255

def ink_for(c):
    return '#101014' if lum(c) > 0.62 else '#ffffff'

# 구단별 평균 몸값 → 디비전 안 순위
score = {}
for cid, rec in merged.items():
    mvs = [p['mv'] for p in rec['picked'] if p['mv']]
    score[cid] = (sum(mvs) / len(mvs)) if mvs else 0

teams_out = []
rosters_out = {}
for (cid, div, name, short, nick, city, stadium, cap, c1, c2, formation, tactic, bio) in CLUBS:
    rec = merged[cid]
    dname, dshort, lo, hi = DIV[div]
    same = [c[0] for c in CLUBS if c[1] == div]
    ranked = sorted(same, key=lambda k: -score.get(k, 0))
    pos = ranked.index(cid) if cid in ranked else len(ranked) - 1
    frac = pos / max(1, len(ranked) - 1)
    power = round(hi - frac * (hi - lo))
    budget = round((hi - frac * (hi - lo)) * {1: 4.5, 2: 1.7, 3: 0.55, 4: 0.22}[div] + {1: 120, 2: 40, 3: 8, 4: 3}[div])
    wage = round(((hi - frac * (hi - lo)) * {1: 62, 2: 26, 3: 9, 4: 4}[div] + {1: 500, 2: 160, 3: 60, 4: 30}[div]) / 10) * 10
    teams_out.append({
        'id': cid, 'div': div, 'name': name, 'short': short, 'nick': nick, 'city': city,
        'stadium': stadium, 'capacity': cap, 'primary': c1, 'secondary': c2, 'ink': ink_for(c1),
        'power': power, 'budget': budget, 'wage': wage, 'formation': formation,
        'tactic': {'line': tactic[0], 'pass': tactic[1], 'press': tactic[2], 'route': tactic[3]},
        'bio': bio,
    })
    picked = rec['picked']
    # 팀 안 서열: 몸값 → 나이(어린 순) → 등번호
    order = sorted(picked, key=lambda p: (-p['mv'], p['age'] or 99, p['num']))
    n = len(order)
    rows = []
    for i, p in enumerate(order):
        off = round((0.5 - i / max(1, n - 1)) * 14)   # +7 ~ -7
        ovr = max(lo - 6, min(hi + 4, power + off))
        rows.append([p['name'], p['pos'], p['age'] or 0, p['num'], ovr])
    # 등번호 0(미정) 은 빈 번호로 남겨 createWorld 가 채웁니다
    rosters_out[cid] = rows

